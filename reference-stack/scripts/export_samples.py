"""Write sample views of the Gold tables to samples/*.md, so a reader sees the output without running anything.

`--check` regenerates the samples in memory and fails when the committed files differ from the build: a drift
gate that CI runs after `dbt build`, the same idea as the generated types checked against the warehouse in CS-02.
"""
from __future__ import annotations

import argparse
import sys
from decimal import Decimal
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parents[1]
DB = ROOT / "dbt" / "reference_stack.duckdb"
OUT = ROOT / "samples"
NOTE = "_Generated by `scripts/export_samples.py` from the DuckDB build. Do not edit by hand; CI checks it._"

QUERIES = {
    "row_counts.md": (
        "Rows per layer",
        """
        select 'raw.orders' as relation, count(*) as rows from raw.orders
        union all select 'raw.order_lines', count(*) from raw.order_lines
        union all select 'raw.inventory_snapshots', count(*) from raw.inventory_snapshots
        union all select 'silver.slv_orders', count(*) from silver.slv_orders
        union all select 'silver.slv_order_lines', count(*) from silver.slv_order_lines
        union all select 'silver.slv_inventory_daily', count(*) from silver.slv_inventory_daily
        union all select 'gold.gld_sales_daily_by_channel', count(*) from gold.gld_sales_daily_by_channel
        union all select 'gold.gld_inventory_needs', count(*) from gold.gld_inventory_needs
        """,
    ),
    "gld_sales_daily_by_channel.md": (
        "Sales by channel, the last seven days",
        """
        select order_date, channel_code, orders, units, net_revenue, cogs, gross_profit, customers
        from gold.gld_sales_daily_by_channel
        where order_date > (select max(order_date) from gold.gld_sales_daily_by_channel) - interval 7 day
        order by order_date desc, channel_code
        """,
    ),
    "gld_inventory_needs.md": (
        "Lines to buy or transfer: Critical first, then Warning, by days of cover",
        """
        select channel_code, sku, product_name, on_hand, on_order, units_per_day, days_of_cover, days_of_cover_note,
               safety_stock, status, recommended_qty, recommended_cases
        from gold.gld_inventory_needs
        where status <> 'OK'
        order by case status when 'Critical' then 0 else 1 end, days_of_cover nulls last, channel_code, sku
        limit 25
        """,
    ),
    "status_by_channel.md": (
        "Status by channel",
        """
        select channel_code, status, count(*) as skus, sum(recommended_qty) as units_recommended
        from gold.gld_inventory_needs
        group by 1, 2
        order by 1, case status when 'Critical' then 0 when 'Warning' then 1 else 2 end
        """,
    ),
}


def cell(value) -> str:
    if value is None:
        return "—"
    if isinstance(value, Decimal):
        return f"{value:f}"
    if isinstance(value, float):
        return f"{value:.2f}"
    return str(value)


def render(title: str, columns: list[str], rows: list[tuple]) -> str:
    lines = [f"# {title}", "", NOTE, "", "| " + " | ".join(columns) + " |", "|" + "---|" * len(columns)]
    lines += ["| " + " | ".join(cell(v) for v in row) + " |" for row in rows]
    return "\n".join(lines) + "\n"


def build() -> dict[str, str]:
    con = duckdb.connect(str(DB), read_only=True)
    out = {}
    for name, (title, sql) in QUERIES.items():
        cur = con.execute(sql)
        columns = [d[0] for d in cur.description]
        out[name] = render(title, columns, cur.fetchall())
    con.close()
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when the committed samples differ from the build")
    args = parser.parse_args()
    if not DB.exists():
        print(f"no build found at {DB}; run `dbt build --profiles-dir .` in reference-stack/dbt first")
        return 2
    files = build()
    if args.check:
        drift = [name for name, text in files.items()
                 if not (OUT / name).exists() or (OUT / name).read_text(encoding="utf8") != text]
        if drift:
            print("samples differ from the build:", ", ".join(drift))
            return 1
        print("samples match the build")
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        (OUT / name).write_text(text, encoding="utf8", newline="\n")
        print(f"samples/{name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
